    private void btnBukaRekeningActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBukaRekeningActionPerformed
String nik = txtNik.getText().trim();
        String noRek = txtNomorRekening.getText().trim();
        String jenisRek = cbJenisRekening.getSelectedItem().toString();
        String strSetoran = txtSetoranAwal.getText().trim();

        if (nik.isEmpty() || noRek.isEmpty() || strSetoran.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih nasabah di tabel dan isi Setoran Awal!");
            return;
        }

        double setoranAwal;
        try {
            setoranAwal = Double.parseDouble(strSetoran);
            if (setoranAwal < 50000) {
                JOptionPane.showMessageDialog(this, "Setoran awal minimal Rp 50.000!");
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Setoran awal harus berupa angka!");
            return;
        }

        String cabangId = "CBG01";
        String sqlGetUserId = "SELECT user_id FROM nasabah WHERE nik = ?";
        String sqlRekening = "INSERT INTO rekening (nomor_rekening, jenis_rekening, saldo, status_rekening, tanggal_buka, cabang_id, nasabah_user_id) VALUES (?, ?, ?, 'Aktif', CURDATE(), ?, ?)";
        String sqlTransaksi = "INSERT INTO transaksi (transaksi_id, jenis_transaksi, jumlah, saldo_setelah, channel, waktu_transaksi, keterangan, nomor_rekening) VALUES (?, 'Setoran Tunai', ?, ?, 'Teller', NOW(), 'Setoran awal pembukaan rekening', ?)";

        Connection conn = null;
        try {
            conn = Koneksi.getConnection();
            conn.setAutoCommit(false);

            String nasabahUserId = null;
            PreparedStatement psUser = conn.prepareStatement(sqlGetUserId);
            psUser.setString(1, nik);
            ResultSet rsUser = psUser.executeQuery();
            if (rsUser.next()) {
                nasabahUserId = rsUser.getString("user_id");
            } else {
                JOptionPane.showMessageDialog(this, "NIK Nasabah tidak ditemukan!");
                return;
            }

            PreparedStatement psRek = conn.prepareStatement(sqlRekening);
            psRek.setString(1, noRek);
            psRek.setString(2, jenisRek);
            psRek.setDouble(3, setoranAwal);
            psRek.setString(4, cabangId);
            psRek.setString(5, nasabahUserId);
            psRek.executeUpdate();

            String trxId = "TRX" + (System.currentTimeMillis() % 10000000);
            PreparedStatement psTrx = conn.prepareStatement(sqlTransaksi);
            psTrx.setString(1, trxId);
            psTrx.setDouble(2, setoranAwal);
            psTrx.setDouble(3, setoranAwal);
            psTrx.setString(4, noRek);
            psTrx.executeUpdate();

            conn.commit();
            JOptionPane.showMessageDialog(this, "Rekening Baru Berhasil Dibuka!\nNomor Rekening: " + noRek);

            resetForm();

        } catch (SQLException e) {
            if (conn != null) try { conn.rollback(); } catch (SQLException ex) {}
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Gagal Buka Rekening: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBukaRekeningActionPerformed

