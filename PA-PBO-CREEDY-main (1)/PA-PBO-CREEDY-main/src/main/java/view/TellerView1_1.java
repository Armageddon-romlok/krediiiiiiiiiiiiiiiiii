    private void loadDataNasabah() {
        DefaultTableModel model = new DefaultTableModel(
            new String[]{"ID Nasabah", "Nama Lengkap", "Email", "Nomor Telepon", "Alamat"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tblNasabah.setModel(model);
        tblNasabah.getTableHeader().setReorderingAllowed(false);

        String sql = "SELECT u.user_id, u.nama_lengkap, u.email, n.no_telepon, n.alamat " +
                     "FROM users u JOIN nasabah n ON u.user_id = n.user_id " +
                     "WHERE u.user_type = 'Nasabah'";

        try (Connection conn = Koneksi.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("user_id"),
                    rs.getString("nama_lengkap"),
                    rs.getString("email"),
                    rs.getString("no_telepon"),
                    rs.getString("alamat")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data nasabah: " + e.getMessage());
        }
    }

