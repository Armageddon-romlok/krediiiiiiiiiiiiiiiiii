    private void tblNasabahMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblNasabahMouseClicked
int selectedRow = tblNasabah.getSelectedRow();
        if (selectedRow != -1) {
            String userId = tblNasabah.getValueAt(selectedRow, 0).toString();

            String sql = "SELECT nik FROM nasabah WHERE user_id = ?";
            try (Connection conn = Koneksi.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sql)) {
                
                ps.setString(1, userId);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        txtNik.setText(rs.getString("nik"));
                    }
                }
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal mengambil NIK: " + e.getMessage());
            }

            // Generate nomor rekening otomatis
            String newNoRek = "550" + (System.currentTimeMillis() % 10000000);
            txtNomorRekening.setText(newNoRek);
        }
    }//GEN-LAST:event_tblNasabahMouseClicked

