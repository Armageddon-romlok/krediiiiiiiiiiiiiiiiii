    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String email = jTextField2.getText().trim();
        String password = jTextField1.getText().trim();

        if (email.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(LoginView.this, 
                "Email dan Password tidak boleh kosong!", 
                "Peringatan", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            java.sql.Connection conn = config.configDB();
            
            // 1. JIKA PILIHAN ROLE ADALAH NASABAH
            if (selectedRole.equals("Nasabah")) {
                String sql = "SELECT * FROM users WHERE email=? AND password=? AND user_type='Nasabah' AND status='Aktif'";
                java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, email);
                pst.setString(2, password);
                java.sql.ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    // SIMPAN SESSION UNTUK NASABAH
                    model.UserSession.setUserId(rs.getString("user_id")); 
                    model.UserSession.setNamaUser(rs.getString("nama_lengkap"));
                    model.UserSession.setRole(rs.getString("user_type"));

                    // Arahkan ke Halaman Nasabah (Bukan AdminView2)
                    new NasabahView1().setVisible(true); // Sesuaikan dengan class View Nasabah Anda
                    this.dispose();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, 
                        "Login Gagal! Akun ini bukan akun Nasabah atau email/password salah.", 
                        "Akses Ditolak", 
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                }
                
            // 2. JIKA PILIHAN ROLE ADALAH PEGAWAI (Teller, Petugas Kredit, Admin)
            } else {
                // Query JOIN antara users dan pegawai
                String sql = "SELECT u.user_id, u.nama_lengkap, p.jabatan " +
                             "FROM users u " +
                             "JOIN pegawai p ON u.user_id = p.user_id " +
                             "WHERE u.email=? AND u.password=? AND p.jabatan=? AND u.status='Aktif'";
                
                java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, email);
                pst.setString(2, password);
                pst.setString(3, selectedRole);
                
                java.sql.ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    // [PERBAIKAN UTAMA] SIMPAN SESSION UNTUK PEGAWAI / ADMIN
                    model.UserSession.setUserId(rs.getString("user_id")); 
                    model.UserSession.setNamaUser(rs.getString("nama_lengkap"));
                    model.UserSession.setRole(rs.getString("jabatan"));

                    // Arahkan ke Halaman GUI masing-masing
                    switch (selectedRole) {
                        case "Admin" -> new AdminView2().setVisible(true);
                        case "Teller" -> new TellerView().setVisible(true); 
                        case "Petugas Kredit" -> new PetugasKreditView1().setVisible(true); 
                    }
                    this.dispose();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, 
                        "Login Gagal! Akun ini tidak memiliki hak akses sebagai " + selectedRole + ".", 
                        "Akses Ditolak", 
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (HeadlessException | SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Terjadi kesalahan database: " + e.getMessage(), 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

