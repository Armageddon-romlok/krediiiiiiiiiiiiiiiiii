    private void tblNasabahMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblNasabahMouseClicked
int selectedRow = tblNasabah.getSelectedRow();
    
    if (selectedRow != -1) {
        // Ambil data dari tabel
        String userId = tblNasabah.getValueAt(selectedRow, 0).toString();
        
        txtNamaLengkap.setText(tblNasabah.getValueAt(selectedRow, 1).toString());
        txtEmail.setText(tblNasabah.getValueAt(selectedRow, 2).toString());
        txtNomorTelepon.setText(tblNasabah.getValueAt(selectedRow, 3).toString());
        txtAlamat.setText(tblNasabah.getValueAt(selectedRow, 4).toString());

        // Ambil NIK dari database berdasarkan user_id baris yang diklik
        try (java.sql.Connection conn = Koneksi.getConnection();
             java.sql.PreparedStatement ps = conn.prepareStatement("SELECT nik FROM nasabah WHERE user_id = ?")) {
            ps.setString(1, userId);
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txtNik.setText(rs.getString("nik"));
                }
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengambil NIK: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_tblNasabahMouseClicked

