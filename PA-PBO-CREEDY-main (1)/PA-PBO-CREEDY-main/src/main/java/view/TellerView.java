    public void loadDataNasabah() {
        DefaultTableModel model = (DefaultTableModel) tblNasabah.getModel();
        model.setRowCount(0);

        String sql = "SELECT u.user_id, u.nama_lengkap, u.email, n.nik, n.no_telepon, n.alamat " +
                     "FROM users u JOIN nasabah n ON u.user_id = n.user_id WHERE u.user_type = 'Nasabah'";

        try (Connection conn = Koneksi.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {

            while (rs.next()) {
                Object[] row = {
                    rs.getString("user_id"),
                    rs.getString("nama_lengkap"),
                    rs.getString("email"),
                    rs.getString("no_telepon"),
                    rs.getString("alamat")
                };
                model.addRow(row);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }

