private void loadDataNasabah(String nasabahId) {
    try {
        Connection conn = config.configDB();
        String sql = "SELECT n.user_id, n.nik, n.npwp, u.nama_lengkap, n.alamat, " +
                     "n.no_telepon, n.tanggal_daftar, n.tipe_nasabah " +
                     "FROM nasabah n " +
                     "INNER JOIN users u ON n.user_id = u.user_id " +
                     "WHERE n.user_id = ?";
                     
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, nasabahId);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            jTextField2.setText(rs.getString("user_id"));
            jTextField3.setText(rs.getString("nik"));
            jTextField4.setText(rs.getString("npwp") != null ? rs.getString("npwp") : "-");
            jTextField6.setText(rs.getString("nama_lengkap"));
            jTextArea1.setText(rs.getString("alamat"));
            jTextField5.setText(rs.getString("no_telepon"));
            jTextField8.setText(rs.getString("tanggal_daftar"));
            jTextField7.setText(rs.getString("tipe_nasabah"));
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal mengambil data profil nasabah: " + e.getMessage());
    }
}

